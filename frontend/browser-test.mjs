import assert from 'node:assert/strict'
import {execFileSync,spawn} from 'node:child_process'
import {resolve} from 'node:path'
import {chromium} from 'playwright'

const cwd=resolve(import.meta.dirname,'..')
const python=process.env.PYTHON || 'python'
const backend=spawn(python,['-B','-m','tests.browser_fixture_server'],{cwd,stdio:['ignore','pipe','inherit']})
let browser
try {
 const origin=await new Promise((resolve,reject)=>{
  const timer=setTimeout(()=>reject(new Error('Fixture server did not start')),10000)
  backend.on('exit',c=>{clearTimeout(timer);reject(new Error('Fixture server exited: '+c))})
  backend.stdout.once('data',data=>{clearTimeout(timer);resolve(data.toString().trim())})
 })
 browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome',headless:true})
 const context=await browser.newContext({baseURL:origin,permissions:['clipboard-read','clipboard-write']})
 const fixture=await context.newPage()
 await fixture.setContent('<form><span id="contact-label">Contact email</span><input id="contact" type="email" aria-labelledby="contact-label" required><fieldset><legend>Preferred shift</legend><label><input type="radio" name="shift" required>Day</label></fieldset><label>Tools<select multiple><option>Python</option><option disabled>Other</option></select></label><label>Start date<input type="date"></label><label>Remote<input type="checkbox"></label><label>Resume<input type="file" accept=".pdf"></label></form>')
 const snapshot=execFileSync(python,['-B','-c','from smartplier.form_engine import FORM_SNAPSHOT; print(FORM_SNAPSHOT)'],{cwd,encoding:'utf8'})
 const {fields}=await fixture.locator('form').evaluate(new Function('form', 'return ('+snapshot+')(form)'))
 assert.deepEqual(fields.map(({type,label})=>[type,label]),[['email','Contact email'],['radio','Day'],['select-multiple','Tools'],['date','Start date'],['checkbox','Remote'],['file','Resume']])
 assert.ok(fields[0].required && fields[0].validation)
 assert.equal(fields[1].group,'Preferred shift')
 assert.equal(fields[2].options[1].disabled,true)
 assert.equal(fields[5].accept,'.pdf')
 await fixture.close()
 const page=await context.newPage()
 page.setDefaultTimeout(10000)
 const errors=[]
 page.on('pageerror',error=>errors.push(String(error)))
 const nav=name=>page.getByRole('navigation',{name:'Workspace'}).getByRole('link',{name,exact:true}).click()
 const ready=name=>page.getByRole('heading',{name,exact:true}).waitFor()
 await page.goto(origin)
 await ready('Job search overview')
 await nav('Discover')
 await ready('Discovery control center')
 await page.getByRole('button',{name:'Discover Jobs Now'}).click()
 await page.getByText('Imported 1 · 0 duplicates',{exact:true}).waitFor()
 await nav('Jobs')
 await page.getByRole('button',{name:'Add job'}).click()
 await page.getByLabel('Title',{exact:true}).fill('Python Developer')
 await page.getByLabel('Company',{exact:true}).fill('Browser test')
 await page.getByLabel('Location',{exact:true}).fill('Remote')
 await page.getByLabel('Description',{exact:true}).fill('Python.\nRecruiter: Priya Sharma')
 await page.getByRole('button',{name:'Save posting'}).click()
 await ready('Python Developer')
 await page.getByText('Application platform · Unknown',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Score job'}).click()
 await page.getByText('83',{exact:false}).filter({visible:true}).first().waitFor()
 await page.getByRole('button',{name:'Open Resume Studio'}).click()
 await page.getByRole('button',{name:'Generate resume'}).click()
 await page.getByRole('link',{name:'Download LaTeX'}).waitFor()
 const downloadable=await page.request.get(await page.getByRole('link',{name:'Download LaTeX'}).getAttribute('href'))
 assert.equal(downloadable.status(),200)
 assert.match(await downloadable.text(),/documentclass/)
 const printPage=await context.newPage()
 await printPage.goto(origin+await page.getByRole('link',{name:'Open preview'}).getAttribute('href'))
 const printable=await printPage.pdf({preferCSSPageSize:true})
 assert.equal((printable.toString('latin1').match(/\/Type\s*\/Page\b/g)||[]).length,1)
 await printPage.close()
 await page.getByRole('button',{name:'Outreach',exact:true}).click()
 await page.getByRole('button',{name:'Draft outreach'}).click()
 await page.getByRole('button',{name:'Copy email',exact:true}).click()
 assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/Hi Priya/)
 await page.getByRole('button',{name:'Details',exact:true}).click()
 await page.locator('select[name=status]').selectOption('applied')
 await page.getByLabel('Resume variant when applying').fill('Tailored')
 await page.getByRole('button',{name:'Update status'}).click()
 await page.getByRole('button',{name:'Record application reply'}).click()
 await nav('Analytics')
 await ready('Application analytics')
 await page.locator('.stat').filter({hasText:'Response rate'}).getByText('100%',{exact:true}).waitFor()
 await nav('Settings')
 await page.getByLabel('Interval in minutes').fill('120')
 await page.getByRole('button',{name:'Save discovery settings'}).first().click()
 await nav('Discover')
 await page.getByText('Checks every 120 minutes',{exact:false}).waitFor()
 await nav('Auto-Apply')
 await ready('Auto-Apply')
 assert.equal(await page.getByRole('button',{name:'Prepare batch preflights'}).isDisabled(),true)
 await page.getByLabel('Minimum Gemini fit').fill('82')
 await page.getByRole('button',{name:'Save rules'}).click()
 await page.getByText('Auto-Apply settings saved.',{exact:true}).waitFor()
 await page.getByRole('heading',{name:'Question inbox'}).waitFor()
 await page.getByText('Which shift do you prefer?',{exact:true}).waitFor()
 await page.getByText('1 job waiting · Select-one · Fixture Employer (Fixture ATS)',{exact:true}).waitFor()
 await page.getByLabel('Verified answer').selectOption('Morning')
 await page.getByRole('button',{name:'Save answer',exact:true}).click()
 await page.getByText('No screening questions are waiting for review.',{exact:true}).waitFor()
 await page.getByRole('row').filter({hasText:'Sample screening job'}).getByText('The posting has no unambiguous publication date.').waitFor()
 assert.deepEqual(errors,[])
 console.log('Browser workflows passed: discovery, jobs, score, resume downloads, outreach, analytics, settings, Auto-Apply and Question Inbox.')
} finally {
 if(browser)await browser.close()
 backend.kill()
}
